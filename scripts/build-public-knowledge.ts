import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {readFoodGuidanceAssets} from '../backend/src/rag/food-guidance-repository';
import {canonicalKnowledgeHash} from '../backend/src/health-knowledge';
import {knownEvidenceWithdrawalIds} from '../backend/src/health-knowledge-policy';
const [out,revocationFile]=process.argv.slice(2);
if(!out||!revocationFile)throw Error('OUTPUT_AND_AUTHORITATIVE_WITHDRAWALS_REQUIRED');
const withdrawn=JSON.parse(await readFile(revocationFile,'utf8'));
if(!Array.isArray(withdrawn)||withdrawn.some(x=>typeof x!=='string'||x.length>300))throw Error('WITHDRAWALS_INVALID');
const a=await readFoodGuidanceAssets(),payload={bundle:a.bundle,goals:a.goals,mappings:a.mappings,expansion:a.expansion};
const revocations=[...new Set([...a.bundle.revocations,...knownEvidenceWithdrawalIds,...withdrawn])].sort();
const releaseId='knowledge-food-guidance-20261113-v1',hash=canonicalKnowledgeHash(payload),dir=resolve(out);
await mkdir(dir,{recursive:false});
const q=(s:string)=>"'"+s.replaceAll("'","''")+"'";
const sql=await readFile('deployment/db/public-knowledge-release.sql','utf8');
await writeFile(join(dir,'publish.sql'),`BEGIN;\n${sql}\nINSERT INTO public.shiwei_knowledge_releases(release_id,checksum,payload,revocations,published) VALUES(${q(releaseId)},${q(hash)},${q(JSON.stringify(payload))}::jsonb,${q(JSON.stringify(revocations))}::jsonb,true);\nNOTIFY pgrst,'reload schema';\nCOMMIT;\n`);
await writeFile(join(dir,'payload.json'),JSON.stringify(payload));
const manifest={releaseId,hash,bytes:Buffer.byteLength(JSON.stringify(payload)),baseKnowledge:a.bundle.id,goals:a.goals.id,mappings:a.mappings.id,nutrition:a.expansion.id,withdrawals:revocations.length,clinicalRelease:null,privateData:false};
await writeFile(join(dir,'manifest.json'),JSON.stringify(manifest,null,2));console.log(JSON.stringify(manifest));
