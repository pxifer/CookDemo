import { readFile,mkdir,writeFile } from 'node:fs/promises';
import { resolve,join } from 'node:path';
import { validateKnowledgeBundle } from '../backend/src/health-knowledge';
import { runRecipeEvidenceTask,evidenceHash,type RecipeEvidenceBinding } from '../backend/src/recipe-evidence';
import type { ContentSnapshot } from '../shared/content';
const read=async(path:string)=>JSON.parse(await readFile(path,'utf8'));
const knowledge=validateKnowledgeBundle(await read('datasets/health/2026-10-28-v2/knowledge-bundle.json'));
const content:ContentSnapshot=await read('datasets/health/recipe-research/recipe-snapshot.json');
const bindings:RecipeEvidenceBinding[]=await read('datasets/health/recipe-research/bindings.json');
const manifest=await read('datasets/health/recipe-research/manifest.json');
if(evidenceHash(content)!==manifest.contentHash||evidenceHash(bindings)!==manifest.bindingsHash||manifest.onlineEnabled!==false)throw Error('RECIPE_PILOT_MANIFEST_MISMATCH');
const revoked=new Set<string>();
const load=async()=>({content,knowledge,revoked});
const target=content.recipes.find(r=>r.name==='白菜豆腐汤')!;
const input={bindings,recipeId:target.id,variantId:target.variants[0].id,load,context:{adult:'yes'}};
const applicable=await runRecipeEvidenceTask(input);
const unknown=await runRecipeEvidenceTask({...input,context:{}});
revoked.add('nhc-hypertension-2023');
const withdrawn=await runRecipeEvidenceTask(input);
const report={scope:'real published recipe / source-bound research annotations; no clinical recipe approval or online activation',recipe:target.name,contentVersion:content.contentVersion,knowledge:knowledge.id,applicable,unknown,withdrawn};
const out=resolve(process.env.RECIPE_EVIDENCE_DIR??'artifacts/acceptance/recipe-evidence-2026-10-29');await mkdir(out,{recursive:true});await writeFile(join(out,'demo.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({recipe:target.name,applicable:applicable.state,unknown:unknown.state,withdrawn:withdrawn.state,bindings:bindings.length,report:join(out,'demo.json')}));
if(applicable.state!=='research_annotations'||unknown.state!=='needs_confirmation'||withdrawn.state!=='withdrawn')process.exitCode=1;
