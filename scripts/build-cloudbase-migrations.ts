import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requiredCoreTables } from '../server/deployment';
import { migrationFiles } from '../server/migrations';

export const cloudbaseTarget = {
  environmentId: 'shiwei-d2gmiun66b7dc6a4f',
  region: 'ap-shanghai',
  database: 'postgres-l3nqdxta',
  owner: 'cloudbase_postgres_postgres_l3nqdxta',
};

type Target = { database: string; owner: string; clientRoles?: string[] };
const literal = (value: string) => `'${value.replace(/'/g, "''")}'`;
const array = (values: string[]) => `ARRAY[${values.map(literal).join(',')}]::text[]`;
function quoteBody(source: string, tag: string) {
  if (source.includes(`$${tag}$`)) throw new Error('SQL_DELIMITER_COLLISION');
  return `$${tag}$${source}$${tag}$`;
}

export async function buildCloudbaseMigration(mode: 'core' | 'vector', target: Target = cloudbaseTarget) {
  const files = await Promise.all(migrationFiles.map(async file => {
    const source = (await readFile(new URL(`../server/migrations/${file.name}`, import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
    return { ...file, checksum: createHash('sha256').update(source).digest('hex'),
      sql: source.replace(/^\s*BEGIN;\s*/i, '').replace(/\s*COMMIT;\s*$/i, '') };
  }));
  const core = ['schema_migrations', ...requiredCoreTables];
  const vector = ['embedding_indexes', 'recipe_variant_embeddings'];
  const clients = target.clientRoles ?? ['anon', 'authenticated', 'service_role'];
  const tables = mode === 'core' ? core : vector;
  const selected = files.filter(file => mode === 'core' ? !file.vector : file.vector);
  const validation = files.map(file => `
    WHEN ${file.version} THEN
      IF installed.filename IS DISTINCT FROM ${literal(file.name)} OR installed.checksum IS DISTINCT FROM ${literal(file.checksum)} THEN
        RAISE EXCEPTION 'MIGRATION_CHANGED_${file.version}';
      END IF;`).join('');
  const applications = selected.map(file => `
  IF NOT EXISTS (SELECT 1 FROM public.schema_migrations WHERE version=${file.version}) THEN
    EXECUTE ${quoteBody(file.sql, `shiwei_source_${file.version}`)};
    INSERT INTO public.schema_migrations(version,filename,checksum)
      VALUES(${file.version},${literal(file.name)},${literal(file.checksum)})
      ON CONFLICT(version) DO UPDATE SET filename=EXCLUDED.filename,checksum=EXCLUDED.checksum;
  END IF;`).join('\n');
  const preflight = mode === 'core' ? `
  IF to_regclass('public.schema_migrations') IS NULL AND EXISTS (
    SELECT 1 FROM pg_tables WHERE schemaname='public' AND tablename=ANY(${array([...core, ...vector])})
  ) THEN RAISE EXCEPTION 'CLOUDBASE_UNTRACKED_PROJECT_TABLES'; END IF;
  CREATE TABLE IF NOT EXISTS public.schema_migrations (
    version integer PRIMARY KEY, installed_at timestamptz NOT NULL DEFAULT now(), filename text, checksum text);
  ALTER TABLE public.schema_migrations ADD COLUMN IF NOT EXISTS filename text;
  ALTER TABLE public.schema_migrations ADD COLUMN IF NOT EXISTS checksum text;` : `
  IF to_regclass('public.schema_migrations') IS NULL THEN
    RAISE EXCEPTION 'CLOUDBASE_CORE_REQUIRED';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.schema_migrations WHERE version=2) THEN
    RAISE EXCEPTION 'CLOUDBASE_CORE_REQUIRED';
  END IF;`;
  const extension = mode === 'vector' ? `
  IF NOT EXISTS (SELECT 1 FROM pg_extension WHERE extname='vector') THEN
    CREATE SCHEMA IF NOT EXISTS extensions;
    CREATE EXTENSION vector WITH SCHEMA extensions;
  END IF;
  SELECT n.nspname INTO extension_schema FROM pg_extension e JOIN pg_namespace n ON n.oid=e.extnamespace WHERE e.extname='vector';
  PERFORM set_config('search_path', 'public,' || quote_ident(extension_schema), true);` : '';
  return `-- Generated by scripts/build-cloudbase-migrations.ts. Reviewed target: ${cloudbaseTarget.environmentId}.
-- Atomic DO statement; keeps the application's original migration checksums.
-- Cloud-specific ACL/RLS changes apply only to this owner's defaults and project tables.
-- No accounts, credentials, catalogue rows, models, or runtime login role are created.
DO $shiwei_deploy$
DECLARE
  installed record;
  recipient text;
  recipient_sql text;
  table_name text;
  table_oid oid;
  owned_sequence record;
  extension_schema text;
BEGIN
  PERFORM pg_advisory_xact_lock(1936226167,1);
  PERFORM set_config('lock_timeout','5s',true);
  -- pg_catalog is implicitly searched first for lookup; public remains the DDL target.
  PERFORM set_config('search_path','public,extensions',true);
  IF current_database() <> ${literal(target.database)} OR current_user <> ${literal(target.owner)} THEN
    RAISE EXCEPTION 'CLOUDBASE_TARGET_MISMATCH';
  END IF;
${preflight}
  FOR installed IN SELECT version,filename,checksum FROM public.schema_migrations ORDER BY version LOOP
    CASE installed.version${validation}
    ELSE RAISE EXCEPTION 'SCHEMA_NEWER_THAN_CODE';
    END CASE;
  END LOOP;
  -- Remove the platform's broad defaults before creating project tables.
  FOREACH recipient IN ARRAY ${array(['PUBLIC', ...clients])} LOOP
    IF recipient='PUBLIC' OR EXISTS (SELECT 1 FROM pg_roles WHERE rolname=recipient) THEN
      recipient_sql := CASE WHEN recipient='PUBLIC' THEN 'PUBLIC' ELSE quote_ident(recipient) END;
      EXECUTE format('ALTER DEFAULT PRIVILEGES FOR ROLE %I IN SCHEMA public REVOKE ALL ON TABLES FROM %s',current_user,recipient_sql);
      EXECUTE format('ALTER DEFAULT PRIVILEGES FOR ROLE %I IN SCHEMA public REVOKE ALL ON SEQUENCES FROM %s',current_user,recipient_sql);
    END IF;
  END LOOP;
${extension}
${applications}
  FOREACH table_name IN ARRAY ${array(tables)} LOOP
    table_oid := to_regclass(format('public.%I',table_name));
    IF table_oid IS NULL OR NOT EXISTS (
      SELECT 1 FROM pg_class WHERE oid=table_oid AND relkind IN ('r','p') AND relowner=(SELECT oid FROM pg_roles WHERE rolname=current_user)
    ) THEN RAISE EXCEPTION 'CLOUDBASE_PROJECT_TABLE_OWNER_MISMATCH: %',table_name; END IF;
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',table_name);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC',table_name);
    FOREACH recipient IN ARRAY ${array(clients)} LOOP
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=recipient) THEN
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM %I',table_name,recipient);
        IF has_table_privilege(recipient,table_oid,'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER,MAINTAIN')
          OR has_any_column_privilege(recipient,table_oid,'SELECT,INSERT,UPDATE,REFERENCES') THEN
          RAISE EXCEPTION 'CLOUDBASE_CLIENT_ACCESS_REMAINS: % %',recipient,table_name;
        END IF;
      END IF;
    END LOOP;
  END LOOP;
  FOR owned_sequence IN
    SELECT DISTINCT s.oid,s.relname,n.nspname,s.relowner FROM pg_class s
    JOIN pg_namespace n ON n.oid=s.relnamespace
    JOIN pg_depend d ON d.objid=s.oid AND d.classid='pg_class'::regclass AND d.refclassid='pg_class'::regclass AND d.deptype IN ('a','i')
    JOIN pg_class t ON t.oid=d.refobjid JOIN pg_namespace tn ON tn.oid=t.relnamespace
    WHERE s.relkind='S' AND tn.nspname='public' AND t.relname=ANY(${array(tables)})
  LOOP
    IF owned_sequence.relowner <> (SELECT oid FROM pg_roles WHERE rolname=current_user) THEN
      RAISE EXCEPTION 'CLOUDBASE_PROJECT_SEQUENCE_OWNER_MISMATCH';
    END IF;
    EXECUTE format('REVOKE ALL ON SEQUENCE %I.%I FROM PUBLIC',owned_sequence.nspname,owned_sequence.relname);
    FOREACH recipient IN ARRAY ${array(clients)} LOOP
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=recipient) THEN
        EXECUTE format('REVOKE ALL ON SEQUENCE %I.%I FROM %I',owned_sequence.nspname,owned_sequence.relname,recipient);
        IF has_sequence_privilege(recipient,owned_sequence.oid,'USAGE,SELECT,UPDATE') THEN
          RAISE EXCEPTION 'CLOUDBASE_CLIENT_SEQUENCE_ACCESS_REMAINS';
        END IF;
      END IF;
    END LOOP;
  END LOOP;
END
$shiwei_deploy$;
`;
}

async function main() {
  const directory = new URL('../cloudbase/migrations/', import.meta.url);
  await mkdir(directory, { recursive: true });
  for (const [mode, filename] of [
    ['core', '20261021123000_shiwei_core.sql'],
    ['vector', '20261021123100_shiwei_vector.sql'],
  ] as const) {
    const sql = await buildCloudbaseMigration(mode);
    const path = new URL(filename, directory);
    try {
      const existing = await readFile(path, 'utf8');
      if (existing.replace(/\r\n/g, '\n') !== sql) throw new Error('EXISTING_CLOUDBASE_MIGRATION_CHANGED_CREATE_A_NEW_VERSION');
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
      await writeFile(path, sql, { encoding: 'utf8', flag: 'wx' });
    }
    console.log(JSON.stringify({ mode, filename, sha256: createHash('sha256').update(sql).digest('hex') }));
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
